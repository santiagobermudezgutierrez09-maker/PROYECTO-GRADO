const PALABRAS_COCCION = /\b(hornea|hornear|horno|cocina|cocinar|calienta|calentar|hierve|hervir|cuece|cocer|fríe|freír|derrite|derretir)\b/i;

// Emoji de cada postre según su nombre (el primero que coincide)
const EMOJIS = [
  [/cupcake|muffin/, "🧁"],
  [/galleta/, "🍪"],
  [/helado|paleta/, "🍨"],
  [/cheesecake|pie /, "🥧"],
  [/brownie|trufa|chocolate/, "🍫"],
  [/calabaza|halloween/, "🎃"],
  [/zanahoria/, "🥕"],
  [/coco|cocada/, "🥥"],
  [/fresa|fruta|manzana|mango|banano|papaya|breva|compota|naranja|pera|maracuy|piña|ensalada/, "🍓"],
  [/avena|yogur|chía|chia|granola|bowl|cottage|barra|bolitas/, "🥣"],
  [/flan|gelatina|mousse|natilla|mazamorra|arroz|pudín|pudin|cuajada|tocino|torrija|natas|dulce de leche/, "🍮"],
  [/torta|panqu|roscón|pan |milhoja|brazo|carlota|pionono|buñuelo|tiramis|merengón/, "🍰"],
  [/arequipe|oblea|bocadillo/, "🍯"],
];

const EMOJI_POR_CATEGORIA = { tradicional: "🍮", fitness: "🥗", especial: "🎉" };

const emojiDe = (receta) => {
  const nombre = receta.nombre.toLowerCase();
  const encontrado = EMOJIS.find(([patron]) => patron.test(nombre));
  return encontrado ? encontrado[1] : EMOJI_POR_CATEGORIA[receta.categoria] || "🍩";
};

export default recetas.map((receta) => {
  const requiereCoccion = receta.pasos.some((paso) => PALABRAS_COCCION.test(paso));
  const tiempoPreparacion = requiereCoccion
    ? Math.round(receta.tiempo * 0.4)
    : receta.tiempo;

  return {
    ...receta,
    emoji: receta.emoji || emojiDe(receta),
    tiempoPreparacion,
    tiempoCoccion: receta.tiempo - tiempoPreparacion,
  };
});